/*
 * Emits src/styles/font-fallbacks.css — metric-matched local fallbacks.
 *
 * `font-display: swap` means the first paint uses a system font and the real
 * face replaces it. If the two occupy different space, that swap reflows the
 * page and CLS is non-zero. Overriding the fallback's ascent, descent, line gap
 * and width so it takes exactly the same room makes the swap invisible.
 *
 * The size-adjust figure is measured, not guessed: the same string is rendered
 * in the real face and in the fallback, and the ratio of the two widths is the
 * adjustment. Run with: npm run fallbacks
 */
import { chromium } from 'playwright';
import * as fontkit from 'fontkit';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHROME = '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';

const FACES = [
  { family: 'Titan One', file: 'titan-one-latin-400-normal.woff2', weight: 400 },
  { family: 'Archivo', file: 'archivo-latin-400-normal.woff2', weight: 400 },
  { family: 'Barlow Condensed', file: 'barlow-condensed-latin-500-normal.woff2', weight: 500 },
];

/* Long enough that per-glyph rounding averages out, and Czech-heavy so the
   accented forms are included in the measurement. */
const SAMPLE = 'Kváskový chléb s konfitovaným česnekem a gochujangem 0123456789';

const metrics = FACES.map((f) => {
  const path = join(root, 'public/fonts', f.file);
  let font = fontkit.openSync(path);
  if (font.fonts) font = font.fonts[0];
  return {
    ...f,
    ascent: font.ascent / font.unitsPerEm,
    descent: Math.abs(font.descent) / font.unitsPerEm,
    lineGap: font.lineGap / font.unitsPerEm,
    b64: readFileSync(path).toString('base64'),
  };
});

const browser = await chromium.launch({ executablePath: CHROME, args: ['--no-sandbox'] });
const page = await browser.newPage();

const measured = [];
for (const m of metrics) {
  const ratio = await page.evaluate(
    async ({ family, b64, sample }) => {
      const face = new FontFace(family, `url(data:font/woff2;base64,${b64})`);
      await face.load();
      document.fonts.add(face);
      const span = document.createElement('span');
      span.style.cssText = 'position:absolute;white-space:nowrap;font-size:100px';
      span.textContent = sample;
      document.body.appendChild(span);

      span.style.fontFamily = 'Arial, sans-serif';
      const fallbackWidth = span.getBoundingClientRect().width;
      span.style.fontFamily = `"${family}"`;
      const realWidth = span.getBoundingClientRect().width;

      span.remove();
      return realWidth / fallbackWidth;
    },
    { family: m.family, b64: m.b64, sample: SAMPLE }
  );
  measured.push({ ...m, sizeAdjust: ratio });
  console.log(`${m.family.padEnd(18)} size-adjust ${(ratio * 100).toFixed(2)}%`);
}
await browser.close();

const css =
  `/* Generated by scripts/build-font-fallbacks.mjs — do not hand-edit.\n` +
  `   Metric-matched fallbacks so the swap from system font to webfont moves\n` +
  `   nothing. size-adjust is measured in a real browser, not estimated. */\n\n` +
  measured
    .map(
      (m) => `@font-face {
  font-family: '${m.family} Fallback';
  src: local('Arial'), local('Helvetica'), local('Liberation Sans');
  size-adjust: ${(m.sizeAdjust * 100).toFixed(2)}%;
  ascent-override: ${((m.ascent / m.sizeAdjust) * 100).toFixed(2)}%;
  descent-override: ${((m.descent / m.sizeAdjust) * 100).toFixed(2)}%;
  line-gap-override: ${((m.lineGap / m.sizeAdjust) * 100).toFixed(2)}%;
}`
    )
    .join('\n\n') + '\n';

writeFileSync(join(root, 'src/styles/font-fallbacks.css'), css);
console.log('wrote src/styles/font-fallbacks.css');
